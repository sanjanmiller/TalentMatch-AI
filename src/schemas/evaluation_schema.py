
"""
Purpose:
    Define validated Pydantic schemas for ranked candidate evaluation by an LLM.

Key responsibilities:
    - Represent one candidate's suitability assessment returned by the LLM.
    - Represent the complete ranked evaluation batch for all supplied candidates.
    - Validate structure, data types, score ranges, and ranking consistency.

The evaluation LLM independently assesses each candidate's overall
suitability against the job description and ranks all supplied candidates.
This schema validates the returned data but does not recalculate or
override any score or ranking position.

Important:
    This schema supports HR decision-making. It does not make hiring decisions.
"""

from pydantic import BaseModel, ConfigDict, Field, model_validator


class CandidateAssessment(BaseModel):
    """Represent the LLM assessment of one candidate."""

    model_config = ConfigDict(extra="forbid")

    candidate_id: str = Field(
        min_length=1,
        description="Internal candidate ID; never a name or email address.",
    )

    rank: int = Field(
        ge=1,
        description=(
            "Ranking position for this candidate; 1 is the most "
            "suitable candidate."
        ),
    )

    overall_score: float = Field(
        ge=0,
        le=10,
        description=(
            "Overall suitability score out of 10, generated by the "
            "evaluation LLM."
        ),
    )

    strengths: list[str] = Field(
        default_factory=list,
        description="Candidate strengths relevant to the job description.",
    )

    relevant_experience: list[str] = Field(
        default_factory=list,
        description="Experience relevant to the job description.",
    )

    skill_gaps: list[str] = Field(
        default_factory=list,
        description="Skills or qualifications the candidate lacks.",
    )

    missing_evidence: list[str] = Field(
        default_factory=list,
        description=(
            "Information that is missing or could not be established "
            "from the supplied resume chunks."
        ),
    )

    supporting_quotes: list[str] = Field(
        default_factory=list,
        description="Relevant excerpts from the supplied resume chunks.",
    )

    explanation: str = Field(
        min_length=1,
        description=(
            "The LLM's overall explanation of the candidate's "
            "suitability assessment."
        ),
    )


class RankedCandidateEvaluations(BaseModel):
    """
    Represent the complete ranked evaluation of all supplied candidates.

    The LLM returns candidates in descending order of overall suitability.
    This container validates ranking consistency:
      - Every candidate appears exactly once (no duplicates).
      - Ranks are exactly 1..N with no gaps.
      - Candidates are listed in rank order.
      - Scores do not increase as the rank position worsens (ties allowed).
    """

    model_config = ConfigDict(extra="forbid")

    candidates: list[CandidateAssessment] = Field(
        min_length=1,
        description="All evaluated candidates ordered by rank, best first.",
    )

    @model_validator(mode="after")
    def check_ranking_consistency(self) -> "RankedCandidateEvaluations":
        """Validate the ranking consistency of the returned candidates."""

        assessments = self.candidates

        # Every candidate must appear exactly once.
        candidate_ids = [
            assessment.candidate_id
            for assessment in assessments
        ]

        if len(candidate_ids) != len(set(candidate_ids)):
            raise ValueError(
                "The evaluation response contains duplicate candidates."
            )

        # Ranks must be exactly 1..N with no gaps, in list order.
        for position, assessment in enumerate(assessments, start=1):
            if assessment.rank != position:
                raise ValueError(
                    "The evaluation response must list candidates in "
                    "rank order, starting from rank 1."
                )

        # Scores must not increase as the rank position worsens.
        for better, worse in zip(assessments, assessments[1:]):
            if worse.overall_score > better.overall_score:
                raise ValueError(
                    "Overall scores must not increase as the ranking "
                    "position worsens."
                )

        return self
